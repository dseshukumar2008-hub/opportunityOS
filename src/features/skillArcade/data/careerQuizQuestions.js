// In-memory cache to prevent repeats of questions
let usedQuestionIds = new Set();

export const getRandomCareerQuestions = (count = 10) => {
  let availableQuestions = careerQuizQuestions.filter(q => !usedQuestionIds.has(q.id));
  
  if (availableQuestions.length < count) {
    availableQuestions = [...careerQuizQuestions];
    usedQuestionIds.clear();
  }

  // Shuffle using Fisher-Yates
  const shuffled = [...availableQuestions];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  
  const selectedQuestions = shuffled.slice(0, count);
  
  // Shuffle options for each question
  const finalizedQuestions = selectedQuestions.map(q => {
    const shuffledOptions = [...q.options];
    for (let i = shuffledOptions.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [shuffledOptions[i], shuffledOptions[j]] = [shuffledOptions[j], shuffledOptions[i]];
    }
    return { ...q, options: shuffledOptions };
  });

  // Accumulate seen IDs
  finalizedQuestions.forEach(q => usedQuestionIds.add(q.id));
  
  return finalizedQuestions;
};

// Clear cache on logout to prevent cross-user leakage
if (typeof window !== 'undefined') {
  window.addEventListener('oppOs_logout', () => {
    usedQuestionIds.clear();
  });
}
